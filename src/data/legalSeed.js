export function getLegalSeed(filters = {}) {
  let list = [...LEGAL_SEED]
  if (filters.type) list = list.filter((i) => i.type === filters.type)
  if (filters.origin) list = list.filter((i) => i.origin === filters.origin)
  if (filters.tag) {
    const t = String(filters.tag).toLowerCase()
    list = list.filter((i) => i.tags.some((x) => x.toLowerCase().includes(t)))
  }
  return list.map((item) => ({
    ...item,
    engagement: {
      completionRate: 0,
      loops: 0,
      shares: 0,
      comments: 0,
      saves: 0,
      earlySkips: 0,
      likes: 0,
    },
    views: 0,
    createdAt: '2026-01-01T00:00:00.000Z',
  }))
}

export function getLegalSeedById(id) {
  return getLegalSeed().find((i) => i.id === id) || null
}
